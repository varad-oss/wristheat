import { useEffect, useState } from 'react';
import { Link, useParams } from 'react-router-dom';
import { getIncident } from '../api';
import { duration, hhmm, hhmmss, num } from '../format';
import type { Incident } from '../types';

const OUTCOME: Record<string, string> = {
  recovered: 'Acknowledged, then recovery confirmed by the data',
  recovered_unacknowledged: 'Recovery confirmed by the data without an acknowledgement',
  not_confirmed: 'Recovery not confirmed within the wait window',
};

export function IncidentDetail() {
  const { id = '' } = useParams();
  const [inc, setInc] = useState<Incident | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let alive = true;
    const load = () => getIncident(id).then((i) => { if (alive) { setInc(i); setError(null); } })
      .catch((e) => alive && setError(e instanceof Error ? e.message : 'load failed'));
    load();
    const t = window.setInterval(load, 5000);
    return () => { alive = false; window.clearInterval(t); };
  }, [id]);

  if (!inc) return <main className="page"><p role="status">{error ? `Couldn't load this incident: ${error}` : 'Loading incident…'}</p></main>;
  const m = inc.metrics;
  const tiles: [string, string][] = [
    ['Time to acknowledge', duration(m?.time_to_ack_s)],
    ['Time to confirmed recovery', duration(m?.time_to_recovery_s)],
    ['Minutes in RED', m ? String(m.minutes_in_red) : '–'],
    ['Peak strain index', num(m?.peak_psi)],
    ['Peak est. core', m?.peak_core_c ? `${num(m.peak_core_c, 2)} °C` : '–'],
  ];
  return (
    <main className="page">
      <p><Link to="/console/incidents">All incidents</Link></p>
      <h1 className="inc-title">
        {inc.trainee_name} {inc.trainee_kind === 'simulated' && <span className="badge badge-sim">SIMULATED</span>}
      </h1>
      <p className="inc-sub">
        RED at {hhmm(inc.opened_at)} ({inc.trigger.rule}). Status {inc.status}
        {inc.outcome ? `: ${OUTCOME[inc.outcome] ?? inc.outcome}` : ''}.
      </p>
      <dl className="tiles">
        {tiles.map(([k, v]) => <div key={k}><dt>{k}</dt><dd className="num">{v}</dd></div>)}
      </dl>
      <section className="report">
        <h2>Report</h2>
        {inc.report ? (
          <>
            <p className="report-src">{inc.report.source === 'bedrock'
              ? 'Summary generated by Amazon Bedrock from the logged events below'
              : 'Template summary (Bedrock unavailable)'}</p>
            <p className="report-text">{inc.report.text}</p>
          </>
        ) : <p>The report is written when the incident closes.</p>}
      </section>
      <section>
        <h2>Timeline</h2>
        <ol className="timeline">
          {inc.events.map((e, i) => (
            <li key={i}><time className="num">{hhmmss(e.t)}</time> <strong>{e.type.replace(/_/g, ' ').toLowerCase()}</strong>{e.detail ? `: ${e.detail}` : ''}</li>
          ))}
        </ol>
        {inc.console_url && <p><a href={inc.console_url} target="_blank" rel="noreferrer">Open in Step Functions console</a></p>}
      </section>
    </main>
  );
}
